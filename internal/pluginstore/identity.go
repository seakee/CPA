// InstallRecordContract is the version of the host-owned installation record.
// It is intentionally independent from the plugin-supplied store manifest.
const InstallRecordContract = 1

// witnessUnsupported is used when the platform has no verified file-instance witness.
const witnessUnsupported = "unsupported"

// ErrInstallArtifactReplaced is returned when the target artifact on disk at
// receipt issuance time is no longer the exact file instance written by the
// controlled installer outcome.
var ErrInstallArtifactReplaced = errors.New("install record: written artifact was replaced before receipt issuance")

// InstallRecord is the host-owned receipt for one controlled plugin install.
// It is persisted in the Management configuration next to the store manifest.
// The instance id is generated by the host at install time; the content digest
// and file witness only prove that the recorded artifact is still the one on
// disk. Neither the digest nor any plugin-reported field is a trust root.
type InstallRecord struct {
	Contract    int         `yaml:"contract" json:"contract"`
	PluginID    string      `yaml:"plugin-id" json:"plugin_id"`
	InstanceID  string      `yaml:"instance-id" json:"instance_id"`
	Version     string      `yaml:"version" json:"version"`
	SourceID    string      `yaml:"source-id" json:"source_id"`
	SourceURL   string      `yaml:"source-url" json:"source_url"`
	Path        string      `yaml:"path" json:"path"`
	SHA256      string      `yaml:"sha256" json:"sha256"`
	Size        int64       `yaml:"size" json:"size"`
	InstalledAt time.Time   `yaml:"installed-at" json:"installed_at"`
	Witness     FileWitness `yaml:"witness" json:"witness"`
}

// FileWitness identifies the file instance, not just its bytes. A delete and
// rewrite of identical bytes produces a different inode/change time and must
// not be accepted as a continuation of the recorded installation.
type FileWitness struct {
	Kind         string `yaml:"kind" json:"kind"`
	Device       uint64 `yaml:"device,omitempty" json:"device,omitempty"`
	Inode        uint64 `yaml:"inode,omitempty" json:"inode,omitempty"`
	ChangeTimeNS int64  `yaml:"change-time-ns,omitempty" json:"change_time_ns,omitempty"`
	BirthTimeNS  int64  `yaml:"birth-time-ns,omitempty" json:"birth_time_ns,omitempty"`
	Size         int64  `yaml:"size,omitempty" json:"size,omitempty"`
}

// NewInstallRecordFromOutcome verifies that the artifact currently on disk at
// result.Path is still the exact file instance and verified archive payload
// written by the controlled installer in result, and issues a new opaque
// installation instance id bound to that write outcome.
func NewInstallRecordFromOutcome(pluginID string, result InstallResult, sourceID, sourceURL string) (InstallRecord, error) {
	pluginID = strings.TrimSpace(pluginID)
	version := strings.TrimSpace(result.Version)
	sourceID = strings.TrimSpace(sourceID)
	sourceURL = strings.TrimSpace(sourceURL)
	if pluginID == "" || !validPluginID(pluginID) {
		return InstallRecord{}, fmt.Errorf("install record: invalid plugin id %q", pluginID)
	}
	if resultID := strings.TrimSpace(result.ID); resultID != "" && resultID != pluginID {
		return InstallRecord{}, fmt.Errorf("install record: result plugin id %q does not match %q", resultID, pluginID)
	}
	if version == "" || !validPluginVersion(version) {
		return InstallRecord{}, fmt.Errorf("install record: invalid plugin version %q", version)
	}
	if sourceID == "" || sourceURL == "" {
		return InstallRecord{}, fmt.Errorf("install record: missing source binding")
	}
	if result.Skipped || result.written.info == nil || strings.TrimSpace(result.written.sha256) == "" || strings.TrimSpace(result.written.path) == "" {
		return InstallRecord{}, fmt.Errorf("install record: missing installer write outcome")
	}
	if !result.written.info.Mode().IsRegular() || result.written.info.Size() != result.written.size {
		return InstallRecord{}, fmt.Errorf("install record: invalid installer write outcome")
	}
	absPath, errAbs := filepath.Abs(result.Path)
	if errAbs != nil {
		return InstallRecord{}, fmt.Errorf("install record: resolve artifact path: %w", errAbs)
	}
	absPath = filepath.Clean(absPath)
	writtenAbsPath, errWrittenAbs := filepath.Abs(result.written.path)
	if errWrittenAbs != nil {
		return InstallRecord{}, fmt.Errorf("install record: resolve outcome artifact path: %w", errWrittenAbs)
	}
	if filepath.Clean(writtenAbsPath) != absPath {
		return InstallRecord{}, fmt.Errorf("install record: outcome path mismatch")
	}
	digest, size, info, errArtifact := inspectArtifact(absPath)
	if errArtifact != nil {
		return InstallRecord{}, fmt.Errorf("%w: %v", ErrInstallArtifactReplaced, errArtifact)
	}
	if !os.SameFile(result.written.info, info) {
		return InstallRecord{}, fmt.Errorf("%w: artifact file instance changed", ErrInstallArtifactReplaced)
	}
	if size != result.written.size || digest != strings.TrimSpace(result.written.sha256) {
		return InstallRecord{}, fmt.Errorf("%w: artifact content changed", ErrInstallArtifactReplaced)
	}
	witness, errWitness := fileWitnessFromInfo(result.written.info)
	if errWitness != nil {
		// A platform without a file witness can still install plugins, but the
		// resulting record is intentionally not qualifiable on read.
		witness = FileWitness{Kind: witnessUnsupported}
	} else if errMatch := witnessMatches(info, witness); errMatch != nil {
		return InstallRecord{}, fmt.Errorf("%w: %v", ErrInstallArtifactReplaced, errMatch)
	}
	instanceID, errID := newInstallInstanceID()
	if errID != nil {
		return InstallRecord{}, errID
	}
	return InstallRecord{
		Contract:    InstallRecordContract,
		PluginID:    pluginID,
		InstanceID:  instanceID,
		Version:     version,
		SourceID:    sourceID,
		SourceURL:   sourceURL,
		Path:        absPath,
		SHA256:      result.written.sha256,
		Size:        result.written.size,
		InstalledAt: time.Now().UTC(),
		Witness:     witness,
	}, nil
}

// Verify checks that the recorded instance still describes the artifact at the
// expected path and that the store/source binding has not changed.
func (r InstallRecord) Verify(pluginID, filePath, version, sourceID, sourceURL string) error {
	if r.Contract != InstallRecordContract {
		return fmt.Errorf("install record: unsupported contract %d", r.Contract)
	}
	if strings.TrimSpace(r.PluginID) != strings.TrimSpace(pluginID) {
		return fmt.Errorf("install record: plugin id changed")
	}
	if !validInstallInstanceID(r.InstanceID) {
		return fmt.Errorf("install record: invalid instance id")
	}
	if strings.TrimSpace(r.Version) != strings.TrimSpace(version) {
		return fmt.Errorf("install record: version changed")
	}
	if strings.TrimSpace(r.SourceID) != strings.TrimSpace(sourceID) {
		return fmt.Errorf("install record: source id changed")
	}
	if strings.TrimSpace(r.SourceURL) != strings.TrimSpace(sourceURL) {
		return fmt.Errorf("install record: source url changed")
	}
	absPath, errAbs := filepath.Abs(filePath)
	if errAbs != nil {
		return fmt.Errorf("install record: resolve artifact path: %w", errAbs)
	}
	absPath = filepath.Clean(absPath)
	if filepath.Clean(r.Path) != absPath {
		return fmt.Errorf("install record: artifact path changed")
	}
	digest, size, info, errArtifact := inspectArtifact(absPath)
	if errArtifact != nil {
		return errArtifact
	}
	if r.Size != size || strings.TrimSpace(r.SHA256) != digest {
		return fmt.Errorf("install record: artifact content changed")
	}
	if errWitness := witnessMatches(info, r.Witness); errWitness != nil {
		return errWitness
	}
	return nil
}

// EncodeInstallRecord returns the YAML node persisted in the plugin config.
func EncodeInstallRecord(record InstallRecord) (*yaml.Node, error) {
	var node yaml.Node
	if errEncode := node.Encode(record); errEncode != nil {
		return nil, fmt.Errorf("encode install record: %w", errEncode)
	}
	return &node, nil
}

// DecodeInstallRecord decodes a persisted install record. A nil/empty node
// means the plugin was not installed through the controlled owner.
func DecodeInstallRecord(node *yaml.Node) (InstallRecord, bool, error) {
	if node == nil || node.Kind == 0 {
		return InstallRecord{}, false, nil
	}
	var record InstallRecord
	if errDecode := node.Decode(&record); errDecode != nil {
		return InstallRecord{}, false, fmt.Errorf("decode install record: %w", errDecode)
	}
	return record, true, nil
}

// InstallPath returns the platform-specific artifact path for a plugin
// version. It is the same path the shared installer writes.
func InstallPath(pluginsDir, goos, goarch, id, version string) (string, error) {
	return installTargetPath(InstallOptions{
		PluginsDir: pluginsDir,
		GOOS:       goos,
		GOARCH:     goarch,
	}, id, version)
}

func inspectArtifact(path string) (string, int64, os.FileInfo, error) {
	linkInfo, errLink := os.Lstat(path)
	if errLink != nil {
		return "", 0, nil, fmt.Errorf("install record: stat artifact: %w", errLink)
	}
	if !linkInfo.Mode().IsRegular() {
		return "", 0, nil, fmt.Errorf("install record: artifact is not a regular file")
	}
	file, errOpen := os.Open(path)
	if errOpen != nil {
		return "", 0, nil, fmt.Errorf("install record: open artifact: %w", errOpen)
	}
	defer func() {
		_ = file.Close()
	}()
	info, errInfo := file.Stat()
	if errInfo != nil {
		return "", 0, nil, fmt.Errorf("install record: stat open artifact: %w", errInfo)
	}
	if !os.SameFile(linkInfo, info) {
		return "", 0, nil, fmt.Errorf("install record: artifact changed while opening")
	}
	if !info.Mode().IsRegular() {
		return "", 0, nil, fmt.Errorf("install record: artifact is not a regular file")
	}
	hasher := sha256.New()
	size, errCopy := io.Copy(hasher, file)
	if errCopy != nil {
		return "", 0, nil, fmt.Errorf("install record: hash artifact: %w", errCopy)
	}
	if size != info.Size() {
		return "", 0, nil, fmt.Errorf("install record: artifact changed while hashing")
	}
	return hex.EncodeToString(hasher.Sum(nil)), size, info, nil
}

func witnessMatches(info os.FileInfo, expected FileWitness) error {
	if strings.TrimSpace(expected.Kind) != witnessKind {
		return fmt.Errorf("install record: file witness is not supported on this platform")
	}
	current, errWitness := fileWitnessFromInfo(info)
	if errWitness != nil {
		return errWitness
	}
	if current.Kind != expected.Kind ||
		current.Device != expected.Device ||
		current.Inode != expected.Inode ||
		current.ChangeTimeNS != expected.ChangeTimeNS ||
		current.BirthTimeNS != expected.BirthTimeNS ||
		current.Size != expected.Size {
		return fmt.Errorf("install record: artifact file instance changed")
	}
	return nil
}

func newInstallInstanceID() (string, error) {
	var raw [16]byte
	if _, errRead := rand.Read(raw[:]); errRead != nil {
		return "", fmt.Errorf("install record: generate instance id: %w", errRead)
	}
	return hex.EncodeToString(raw[:]), nil
}

func validInstallInstanceID(id string) bool {
	id = strings.TrimSpace(id)
	if len(id) != 32 {
		return false
	}
	_, errDecode := hex.DecodeString(id)
	return errDecode == nil
}
